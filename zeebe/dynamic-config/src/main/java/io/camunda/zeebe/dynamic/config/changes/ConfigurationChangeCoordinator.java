package io.camunda.zeebe.dynamic.config.changes;

import io.camunda.zeebe.dynamic.config.state.ClusterConfiguration;
import io.camunda.zeebe.dynamic.config.state.ClusterConfigurationChangeOperation;
import io.camunda.zeebe.dynamic.config.state.CurrentClusterConfiguration;
import io.camunda.zeebe.dynamic.config.state.PhasedChangePlan.Phase;
import io.camunda.zeebe.scheduler.future.ActorFuture;
import io.camunda.zeebe.util.Either;
import java.util.List;
import org.jspecify.annotations.NullMarked;

public interface ConfigurationChangeCoordinator {

  /**
   * @return the current cluster configuration, in its multi-partition-group form.
   */
  ActorFuture<CurrentClusterConfiguration> getClusterConfiguration();

  /**
   * Applies the operations generated by the requestTransformer to the current cluster
   * configuration. If no operations is returned by requestTransformer, the future completes
   * successfully with no change to the cluster configuration.
   *
   * @param requestTransformer the request transformer that generates the operations to apply
   * @return a future which is completed when the configuration change has started successfully.
   */
  ActorFuture<ConfigurationChangeResult> applyOperations(
      ConfigurationChangeRequest requestTransformer);

  /**
   * Simulates the operations generated by the request transformer on the current cluster
   * configuration. Operations are not applied and the current cluster configuration remains
   * unchanged.
   *
   * @param requestTransformer the request transformer that generates the operations to simulate
   * @return a future which is completed with the results of the simulation or an exception
   *     describing why the operations are not valid.
   */
  ActorFuture<ConfigurationChangeResult> simulateOperations(
      ConfigurationChangeRequest requestTransformer);

  /**
   * Cancels a configuration change. This is an unsafe operation and should be called only when the
   * operation is stuck and cannot make progress on its own. When a change is cancelled, already
   * applied operations are not reverted. So the ClusterConfiguration will be in an intermediate
   * state with partially applied operations.
   *
   * @param changeId the id of the change to cancel
   * @return a future which is completed when the change has been cancelled successfully.
   */
  ActorFuture<CurrentClusterConfiguration> cancelChange(long changeId);

  @NullMarked
  record ConfigurationChangeResult(
      // The current configuration before applying the operations, projected to the legacy
      // default-group view.
      ClusterConfiguration currentConfiguration,
      // The expected final configuration after applying the operations, projected to the legacy
      // default-group view.
      ClusterConfiguration finalConfiguration,
      // The current configuration before applying the operations, on the new multi-partition-group
      // model.
      CurrentClusterConfiguration currentMultiConfiguration,
      // The expected final configuration after applying the operations, on the new
      // multi-partition-group model.
      CurrentClusterConfiguration finalMultiConfiguration,
      long changeId,
      // The operations that will be applied to the current configuration.
      List<ClusterConfigurationChangeOperation> legacyOperations,
      List<Phase> phases) {}

  @FunctionalInterface
  interface ConfigurationChangeRequest {

    /**
     * Returns the phases to execute for this request. A phase is applied to the sub-configurations
     * it targets — {@link io.camunda.zeebe.dynamic.config.state.PhasedChangePlan.GlobalPhase} to
     * the cluster-wide broker lifecycle, {@link
     * io.camunda.zeebe.dynamic.config.state.PhasedChangePlan.PartitionGroupPhase} to each named
     * physical tenant's partition group at once — and one phase is fully drained before the next
     * begins.
     *
     * <p>A request that plans partition work has to decide which physical tenants it applies to.
     * There is no cluster-wide default to fall back on: partition ids restart at 1 in every tenant,
     * so a partition is only identified together with the tenant that owns it.
     *
     * @param clusterConfiguration the current cluster configuration
     * @return Either with the list of phases to apply or an exception if the request is not valid.
     */
    Either<Exception, List<Phase>> phases(final CurrentClusterConfiguration clusterConfiguration);

    default boolean isForced() {
      return false;
    }

    /**
     * Whether {@link #phases(CurrentClusterConfiguration)} should see disabled physical tenants
     * (see {@link CurrentClusterConfiguration#activePartitionGroups()}). Defaults to {@code false}:
     * the coordinator passes a view with disabled partition groups removed, so a request that
     * enumerates "all physical tenants" when none is explicitly targeted automatically skips
     * disabled ones, and a request that explicitly targets a disabled tenant by id sees it as
     * absent. Override to {@code true} for a request that must operate on disabled tenants as well,
     * e.g. one that manages tenant availability itself.
     */
    default boolean applyToDisabledTenants() {
      return false;
    }
  }
}
