package io.camunda.zeebe.msgpack.pojo.processor;

import java.util.Comparator;
import java.util.HashMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/** The license header and the placeholders of the generated sources. */
final class Templates {
  static final String HEADER =
      """
      /*
       * Copyright Camunda Services GmbH and/or licensed to Camunda Services GmbH under
       * one or more contributor license agreements. See the NOTICE file distributed
       * with this work for additional information regarding copyright ownership.
       * Licensed under the Camunda License 1.0. You may not use this file
       * except in compliance with the Camunda License 1.0.
       */
      // Generated by MsgpackPojoProcessor, do not edit.
      """;

  private Templates() {}

  /**
   * Replaces the placeholders of a template, such as {@code $field}, by their values. It replaces
   * in one pass: the longest name matches first, and a value is not searched for placeholders. A
   * placeholder for a section stands alone on its line and ends with {@code \}, because the section
   * ends with its own line break.
   */
  static String fill(final String template, final Object... namesAndValues) {
    final var values = new HashMap<String, String>();
    for (int i = 0; i < namesAndValues.length; i += 2) {
      values.put((String) namesAndValues[i], String.valueOf(namesAndValues[i + 1]));
    }
    final var names =
        values.keySet().stream()
            .sorted(Comparator.comparingInt(String::length).reversed())
            .map(Pattern::quote)
            .collect(Collectors.joining("|"));
    return Pattern.compile(names)
        .matcher(template)
        .replaceAll(match -> Matcher.quoteReplacement(values.get(match.group())));
  }

  /**
   * Like {@link #fill(String, Object...)}, with the placeholders of the property: {@code $field},
   * {@code $key} and {@code $type}.
   */
  static String fill(final Property p, final String template, final Object... more) {
    final Object[] property = {
      "$field", p.field(),
      "$key", p.keyLiteral(),
      "$type", p.javaType()
    };
    return fill(template, Stream.concat(Stream.of(property), Stream.of(more)).toArray());
  }

  /**
   * The loop over {@code list} that surrounds {@code body}, which renders one element. The loop
   * variable has the depth in its name ({@code i0}, {@code i1}, ...), so the loops of the levels of
   * a list of lists do not clash.
   */
  static String loop(final String list, final int depth, final String body) {
    return fill(
        """
        for (int $i = 0; $i < $list.size(); $i++) {
        $body\
        }
        """,
        "$list",
        list,
        "$i",
        "i" + depth,
        "$body",
        body.indent(2));
  }
}
