package io.camunda.zeebe.db.rdbms;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Locale;
import org.junit.jupiter.api.Test;

/**
 * Generates the changelog that creates the state tables from {@link StateTables}, and checks that
 * the committed changelog is up to date. Writing about 145 change sets by hand would be
 * error-prone.
 */
final class StateChangelogTest {

  private static final Path CHANGELOG =
      Path.of("src/main/resources/db/changelog/zeebe-state/changesets/8.11.0.xml");
  private static final String REGENERATE = "zeebe.state.regenerate-changelog";

  private static final String HEADER =
      """
      <?xml version="1.0" encoding="UTF-8"?>
      <!--
        ~ Copyright Camunda Services GmbH and/or licensed to Camunda Services GmbH under
        ~ one or more contributor license agreements. See the NOTICE file distributed
        ~ with this work for additional information regarding copyright ownership.
        ~ Licensed under the Camunda License 1.0. You may not use this file
        ~ except in compliance with the Camunda License 1.0.
        -->
      <!--suppress LiquibaseXmlUnresolvedProperty -->
      <databaseChangeLog xmlns="http://www.liquibase.org/xml/ns/dbchangelog"
        xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://www.liquibase.org/xml/ns/dbchangelog
              http://www.liquibase.org/xml/ns/dbchangelog/dbchangelog-latest.xsd">

        <!--
          Generated by StateChangelogTest from StateTables: don't edit it by hand.

          Keys and values are compared byte by byte as unsigned numbers by both types, which gives the
          same key order as RocksDB. Avoid BLOB types: H2 stores them out of the row, and Liquibase maps
          them to OID on PostgreSQL.
        -->
        <property name="binaryType" value="VARBINARY" dbms="h2"/>
        <property name="binaryType" value="BYTEA" dbms="postgresql"/>
      """;

  private static final String FOOTER =
      """

      </databaseChangeLog>
      """;

  @Test
  void shouldCreateEveryStateTable() throws IOException {
    // given
    final var generated = generate();
    if (Boolean.getBoolean(REGENERATE)) {
      Files.writeString(CHANGELOG, generated);
    }

    // when
    final var committed = Files.readString(CHANGELOG);

    // then
    assertThat(committed)
        .describedAs(
            "Expected %s to create the tables of StateTables; regenerate it with: "
                + "./mvnw test -pl zeebe/zb-db/rdbms -Dtest=StateChangelogTest -D%s=true",
            CHANGELOG, REGENERATE)
        .isEqualTo(generated);
  }

  private static String generate() {
    final var changelog = new StringBuilder(HEADER);
    changelog.append(
        changeSet(
            StateTables.PARTITION,
            """
                  <column name="PARTITION_ID" type="INTEGER">
                    <constraints primaryKey="true" primaryKeyName="${prefix}%s"/>
                  </column>
                  <column name="STATE_ID" type="VARCHAR(36)">
                    <constraints nullable="false"/>
                  </column>
                  <column name="OWNER_TERM" type="BIGINT">
                    <constraints nullable="false"/>
                  </column>
                  <column name="WRITTEN_POSITION" type="BIGINT">
                    <constraints nullable="false"/>
                  </column>
            """
                .formatted(StateTables.PARTITION + "_PK")));
    for (final var table : StateTables.all()) {
      changelog.append(changeSet(table.name(), rowColumns(table)));
    }
    return changelog.append(FOOTER).toString();
  }

  private static String rowColumns(final StateTable table) {
    final var primaryKey =
        "<constraints primaryKey=\"true\" primaryKeyName=\"${prefix}%s\"/>"
            .formatted(table.primaryKeyName());
    final var columnFamily =
        table.shared()
            ? """
                  <column name="COLUMN_FAMILY" type="INTEGER">
                    %s
                  </column>
            """
                .formatted(primaryKey)
            : "";
    return """
              <column name="PARTITION_ID" type="INTEGER">
                %s
              </column>
        %s      <column name="STATE_KEY" type="${binaryType}">
                %s
              </column>
              <column name="STATE_VALUE" type="${binaryType}">
                <constraints nullable="false"/>
              </column>
              <column name="UPDATED_POSITION" type="BIGINT">
                <constraints nullable="false"/>
              </column>
        """
        .formatted(primaryKey, columnFamily, primaryKey);
  }

  private static String changeSet(final String table, final String columns) {
    return """

          <changeSet id="create_%s_table" author="camunda">
            <preConditions onFail="MARK_RAN">
              <not>
                <tableExists tableName="${prefix}%s"/>
              </not>
            </preConditions>
            <createTable tableName="${prefix}%s">
        %s    </createTable>
          </changeSet>
        """
        .formatted(table.toLowerCase(Locale.ROOT), table, table, columns);
  }
}
