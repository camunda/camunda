/**
 * Generates the screenshots for the Tasklist "Overview" docs page:
 * https://docs.camunda.io/docs/next/components/tasklist/userguide/using-tasklist/
 *
 * tasklist-with-variables-claimed-by-me_light.png and tasklist-default-filters.png are shared with
 * other pages and generated by managing-tasks.test.ts and using-filters.test.ts.
 */

import {test, expect} from '#/pw-modules/test-extend';
import {HttpResponse} from 'msw';
import {
	mockCurrentUserEndpoint,
	mockGetProcessDefinitionXmlEndpoint,
	mockGetUserTaskEndpoint,
	mockGetUserTaskFormEndpoint,
	mockLicenseEndpoint,
	mockQueryUserTasksEndpoint,
	mockQueryVariablesByUserTaskEndpoint,
	mockSystemConfigurationEndpoint,
} from '#/shared-test-modules/mock-handlers';
import {createSystemConfiguration} from '#/shared-test-modules/api-mocks/system-configuration';
import {createLicense} from '#/shared-test-modules/api-mocks/license';
import {createCurrentUser} from '#/shared-test-modules/api-mocks/current-user';
import {createQueryUserTasksResponse, createUserTask} from '#/shared-test-modules/api-mocks/user-tasks';
import {createUserTaskFormResponse} from '#/shared-test-modules/api-mocks/forms';
import {createQueryVariablesByUserTaskResponse} from '#/shared-test-modules/api-mocks/variables';
import {FLIGHT_REGISTRATION_BPMN_XML} from '#/shared-test-modules/api-mocks/process-definition-xmls';
import {addCallouts, frameApp, getBox, isolateElements, padBox, transformApp} from '../callouts';
import {getScreenshotPath} from '../screenshot-path';

const NOW = new Date('2024-09-05T13:32:00.000Z');
const CREATION_DATE = '2024-09-05T13:15:00.000Z';
const FORM_KEY = '2251799813685290';

const flightRegistrationTask = {
	name: 'Register the passenger',
	processName: 'Flight registration',
	processDefinitionId: 'flightRegistration',
	processDefinitionVersion: 1,
	elementId: 'registerPassenger',
	candidateGroups: ['group1', 'group2'],
	formKey: FORM_KEY,
	priority: 60,
	creationDate: CREATION_DATE,
	dueDate: '2024-09-10T13:15:00.000Z',
	followUpDate: '2024-09-09T13:15:00.000Z',
};

const unassignedPassengerTask = createUserTask({
	...flightRegistrationTask,
	userTaskKey: '2251799813685601',
	assignee: null,
});
const assignedPassengerTask = createUserTask({
	...flightRegistrationTask,
	userTaskKey: '2251799813685602',
	assignee: 'demo',
});
const checkPaymentTask = createUserTask({
	userTaskKey: '2251799813685603',
	name: 'Check payment',
	processName: 'Order process',
	assignee: 'demo',
	priority: 60,
	creationDate: CREATION_DATE,
	dueDate: '2024-09-06T13:15:00.000Z',
});
const approveLoanTask = createUserTask({
	userTaskKey: '2251799813685604',
	name: 'Approve loan',
	processName: 'Credit request',
	assignee: 'john.doe',
	priority: 50,
	creationDate: '2024-09-02T09:30:00.000Z',
	followUpDate: '2024-09-08T09:00:00.000Z',
	dueDate: '2024-09-12T17:00:00.000Z',
});
const registerCarTask = createUserTask({
	userTaskKey: '2251799813685605',
	name: 'Register car for rent',
	processName: 'Car rental',
	assignee: null,
	priority: 90,
	creationDate: '2024-09-04T15:00:00.000Z',
	dueDate: '2024-09-07T12:00:00.000Z',
});
const reviewOrderTask = createUserTask({
	userTaskKey: '2251799813685606',
	name: 'Review order',
	processName: 'Order process',
	assignee: 'demo',
	priority: 10,
	creationDate: '2024-09-03T11:00:00.000Z',
});

const ALL_OPEN_TASKS = [
	unassignedPassengerTask,
	checkPaymentTask,
	approveLoanTask,
	registerCarTask,
	assignedPassengerTask,
	reviewOrderTask,
];

test.beforeEach(async ({network, page, tasklistIndexPage, taskDetailPage}) => {
	network.use(
		mockCurrentUserEndpoint({
			successResponse: HttpResponse.json(createCurrentUser({username: 'demo'})),
		}),
		mockSystemConfigurationEndpoint({
			successResponse: HttpResponse.json(createSystemConfiguration({components: {active: ['tasklist']}})),
		}),
		mockLicenseEndpoint({
			successResponse: HttpResponse.json(createLicense()),
		}),
		mockQueryUserTasksEndpoint({
			successResponse: HttpResponse.json(createQueryUserTasksResponse({items: ALL_OPEN_TASKS})),
		}),
		// The router preloads task details when the pointer hovers a task card (defaultPreload: 'intent')
		mockGetUserTaskEndpoint({
			successResponse: HttpResponse.json(assignedPassengerTask),
		}),
		mockQueryVariablesByUserTaskEndpoint({
			successResponse: HttpResponse.json(createQueryVariablesByUserTaskResponse()),
		}),
		mockGetUserTaskFormEndpoint({
			successResponse: HttpResponse.json(createUserTaskFormResponse({formKey: FORM_KEY})),
		}),
	);

	await page.clock.setFixedTime(NOW);
	await taskDetailPage.seedHideNotificationBanner();
	await tasklistIndexPage.seedHasCompletedTask();
});

test.describe('using-tasklist', () => {
	test('tasks page layout', async ({network, tasklistIndexPage, taskDetailPage, page}) => {
		network.use(
			mockGetUserTaskEndpoint({
				successResponse: HttpResponse.json(unassignedPassengerTask),
			}),
		);

		await taskDetailPage.goto(unassignedPassengerTask.userTaskKey);
		await expect(taskDetailPage.detailsInfo).toBeVisible();
		await expect(taskDetailPage.assignButton).toBeVisible();
		await expect(taskDetailPage.taskTabContent.getByLabel(/^First name/)).toBeVisible();
		await expect(tasklistIndexPage.taskItem('Review order')).toBeVisible();

		await frameApp(page, {scale: 0.84});
		await addCallouts(page, [
			{label: 'Filters', target: tasklistIndexPage.filterSelect, side: 'left', distance: 96, outline: true},
			{label: 'Tasks queue', target: tasklistIndexPage.tasksPanel, side: 'top', distance: 24, outline: true},
			{
				label: 'Task card',
				target: tasklistIndexPage.tasksPanel.getByRole('article').nth(1),
				side: 'left',
				distance: 64,
				outline: true,
			},
			{label: 'Selected task details', target: taskDetailPage.detailsInfo, side: 'top', distance: 24, outline: true},
			{
				label: 'Form',
				target: taskDetailPage.taskTabContent.locator('.fjs-form'),
				side: 'bottom',
				distance: 32,
				outline: true,
			},
			{
				label: 'Task summary',
				target: taskDetailPage.aside.getByText('Follow up date', {exact: true}).locator('..'),
				side: 'bottom',
				distance: 40,
			},
		]);

		await page.screenshot({
			path: getScreenshotPath({
				baseUrl: import.meta.url,
				folder: 'using-tasklist',
				fileName: 'tasklist-page-specifications.png',
			}),
		});
	});

	test('task card attributes', async ({network, tasklistIndexPage, page}) => {
		network.use(
			mockQueryUserTasksEndpoint({
				successResponse: HttpResponse.json(createQueryUserTasksResponse({items: [checkPaymentTask, approveLoanTask]})),
			}),
		);

		await tasklistIndexPage.goto();
		await expect(tasklistIndexPage.taskItem('Check payment')).toBeVisible();
		await expect(tasklistIndexPage.taskItem('Approve loan')).toBeVisible();

		const firstCard = tasklistIndexPage.taskCard('Check payment');
		const secondCard = tasklistIndexPage.taskCard('Approve loan');
		const scale = 1.6;
		const firstCardBox = await getBox(firstCard);

		await transformApp(page, {scale, x: 520 - firstCardBox.x * scale, y: 60 - firstCardBox.y * scale});
		await isolateElements(page, [firstCard, secondCard]);

		const bounds = await addCallouts(page, [
			{label: 'Task name', target: firstCard.getByText('Check payment', {exact: true}), side: 'left'},
			{
				label: 'Process name',
				target: firstCard.getByText('Order process', {exact: true}),
				side: 'right',
				offset: -40,
				fitText: true,
			},
			{label: 'Assignee', target: firstCard.getByTitle('Task assigned to me'), side: 'left'},
			{label: 'Priority', target: firstCard.getByTitle('Priority: High'), side: 'right'},
			{label: 'Creation date', target: firstCard.getByTitle(/^Created /), side: 'left'},
			{
				label: 'Due / Follow up date',
				target: [firstCard.getByTitle(/^Due /), secondCard.getByTitle(/^Follow-up /)],
				side: 'right',
			},
		]);

		await page.screenshot({
			path: getScreenshotPath({
				baseUrl: import.meta.url,
				folder: 'using-tasklist',
				fileName: 'task-tile-specification.png',
			}),
			clip: padBox(page, bounds, 24),
		});
	});

	test('task details form', async ({network, taskDetailPage, page}) => {
		network.use(
			mockGetUserTaskEndpoint({
				successResponse: HttpResponse.json(assignedPassengerTask),
			}),
		);

		await taskDetailPage.goto(assignedPassengerTask.userTaskKey);
		await expect(taskDetailPage.taskName('Register the passenger')).toBeVisible();
		await expect(taskDetailPage.unassignButton).toBeVisible();
		await expect(taskDetailPage.taskTabContent.getByLabel(/^First name/)).toBeVisible();
		await expect(taskDetailPage.completeTaskButton).toBeVisible();

		await page.screenshot({
			path: getScreenshotPath({
				baseUrl: import.meta.url,
				folder: 'using-tasklist',
				fileName: 'tasklist-task-details-form.png',
			}),
		});
	});

	test('process diagram', async ({network, taskDetailPage, page}) => {
		network.use(
			mockGetUserTaskEndpoint({
				successResponse: HttpResponse.json(assignedPassengerTask),
			}),
			mockGetProcessDefinitionXmlEndpoint({
				successResponse: new HttpResponse(FLIGHT_REGISTRATION_BPMN_XML, {headers: {'Content-Type': 'text/xml'}}),
			}),
		);

		await taskDetailPage.gotoProcess(assignedPassengerTask.userTaskKey);
		await expect(taskDetailPage.processName('Flight registration')).toBeVisible();
		await expect(taskDetailPage.processVersion(1)).toBeVisible();
		await expect(taskDetailPage.processDiagramZoomReset).toBeVisible();
		await expect(taskDetailPage.processTabContent.locator('[data-element-id="registerPassenger"]')).toBeVisible();

		await page.screenshot({
			path: getScreenshotPath({
				baseUrl: import.meta.url,
				folder: 'using-tasklist',
				fileName: 'tasklist-task-details-process-diagram.png',
			}),
		});
	});

	test('task ordering', async ({tasklistIndexPage, page}) => {
		await tasklistIndexPage.goto();
		await expect(tasklistIndexPage.taskItem('Review order')).toBeVisible();
		await tasklistIndexPage.openSortMenu();
		await expect(tasklistIndexPage.sortOption('Creation date')).toBeVisible();
		await expect(tasklistIndexPage.sortOption('Due date')).toBeVisible();
		await expect(tasklistIndexPage.sortOption('Follow-up date')).toBeVisible();
		await expect(tasklistIndexPage.sortOption('Priority')).toBeVisible();

		await page.screenshot({
			path: getScreenshotPath({
				baseUrl: import.meta.url,
				folder: 'using-tasklist',
				fileName: 'tasklist-task-ordering.png',
			}),
		});
	});

	test('order icon', async ({tasklistIndexPage}) => {
		await tasklistIndexPage.goto();
		await expect(tasklistIndexPage.taskItem('Review order')).toBeVisible();
		await expect(tasklistIndexPage.sortButton).toBeVisible();

		await tasklistIndexPage.sortButton.screenshot({
			path: getScreenshotPath({baseUrl: import.meta.url, folder: 'using-tasklist', fileName: 'order-icon.png'}),
		});
	});
});
