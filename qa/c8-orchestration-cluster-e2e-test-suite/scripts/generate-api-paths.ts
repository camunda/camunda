/**
 * Emits the `ApiPath` union consumed by `buildUrl` from the REST API spec.
 *
 * Run via `npm run paths:regenerate`.
 *
 * The spec lives in this same repository, so the file is read from the local
 * checkout rather than fetched from GitHub the way `responses:regenerate`
 * does — a local read cannot drift from the branch being tested.
 *
 * Only the top-level `paths:` keys are needed, and in `rest-api.yaml` those
 * keys are already the literal path strings (their values are just `$ref`s
 * into sibling files). That is what makes a line scan sufficient here and
 * keeps the suite free of a YAML-parser dependency.
 */

import {readFileSync, existsSync, mkdirSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';

// The spec moved under `v2/` after 8.8, and each branch carries its own copy of
// this suite, so the location has to be resolved rather than assumed. Order is
// load-bearing: on the post-move branches the old path still exists as a
// relocation stub with no `paths:` block, so the `v2/` location must win.
const SPEC_CANDIDATES = [
  '../../zeebe/gateway-protocol/src/main/proto/v2/rest-api.yaml',
  '../../zeebe/gateway-protocol/src/main/proto/rest-api.yaml',
].map((relative) => join(process.cwd(), relative));

const SPEC_PATH = SPEC_CANDIDATES.find((candidate) => existsSync(candidate));
if (!SPEC_PATH) {
  throw new Error(
    `No REST API spec found. Looked in:\n  ${SPEC_CANDIDATES.join('\n  ')}`,
  );
}
const OUTPUT_PATH = join(process.cwd(), 'utils/_generated/apiPaths.ts');

const LICENSE_HEADER = `/*
 * Copyright Camunda Services GmbH and/or licensed to Camunda Services GmbH under
 * one or more contributor license agreements. See the NOTICE file distributed
 * with this work for additional information regarding copyright ownership.
 * Licensed under the Camunda License 1.0. You may not use this file
 * except in compliance with the Camunda License 1.0.
 */`;

/** Matches a `paths:` child key, tolerating a trailing `# comment`. */
const PATH_KEY = /^ {2}(\/[^:\s]*):(?:\s|$)/;

function extractPaths(spec: string): string[] {
  // `.gitattributes` does not normalise line endings, so a Windows checkout
  // yields CRLF and every line would carry a trailing `\r`.
  const lines = spec.split('\n').map((line) => line.replace(/\r$/, ''));
  const start = lines.findIndex((line) => /^paths:\s*$/.test(line));
  if (start === -1) {
    throw new Error(`No top-level "paths:" block found in ${SPEC_PATH}`);
  }

  const paths: string[] = [];
  const seen = new Set<string>();
  for (const line of lines.slice(start + 1)) {
    // Any other column-0 key ends the block.
    if (/^[^\s#]/.test(line)) break;
    const match = PATH_KEY.exec(line);
    if (!match) continue;
    const path = match[1];
    if (seen.has(path)) {
      throw new Error(`Duplicate path key "${path}" in ${SPEC_PATH}`);
    }
    seen.add(path);
    paths.push(path);
  }

  if (paths.length === 0) {
    throw new Error(`Parsed 0 paths from ${SPEC_PATH} — spec layout changed?`);
  }
  return paths;
}

function render(paths: string[]): string {
  // Sorted rather than in spec order so that regrouping endpoints in the spec
  // produces no diff here.
  const members = [...paths]
    .sort()
    .map((path) => `  | '${path}'`)
    .join('\n');

  return `${LICENSE_HEADER}

/* Auto-generated by \`npm run paths:regenerate\`. Do not edit manually. */

/**
 * Every path declared in \`rest-api.yaml\`, as a literal union.
 *
 * Deliberately not \`RoutePath\` from \`json-body-assertions/_generated\`: that
 * type is derived from response schemas, so it omits every endpoint whose
 * responses carry no JSON body (\`/jobs/{jobKey}/completion\` and friends).
 */
export type ApiPath =
${members};
`;
}

const paths = extractPaths(readFileSync(SPEC_PATH, 'utf8'));
mkdirSync(dirname(OUTPUT_PATH), {recursive: true});
writeFileSync(OUTPUT_PATH, render(paths));
console.log(`Wrote ${paths.length} paths to ${OUTPUT_PATH}`);
